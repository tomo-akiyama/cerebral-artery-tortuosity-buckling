#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate paper table outputs: 13_Table_age_related_visibility."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

STATISTICS_ROOT = Path(__file__).resolve().parent
TABLES_ROOT = STATISTICS_ROOT / "tables"
if str(TABLES_ROOT) not in sys.path:
    sys.path.insert(0, str(TABLES_ROOT))

from table_format import format_est_ci_cell, format_p_value  # noqa: E402

OUT_TEX = TABLES_ROOT / "Table_age_related_visibility.tex"


def _load_visibility():
    path = STATISTICS_ROOT / "12_buckling_visibility.py"
    spec = importlib.util.spec_from_file_location("buckling_visibility", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _age_effect(mod, agg, y_col: str, cov_terms: list[str]) -> tuple[float, float, float, float]:
    res, _work = mod.fit_age_ols(agg, y_col, cov_terms)
    beta = float(res.params["AGE"])
    ci_low, ci_high = res.conf_int().loc["AGE"]
    return beta, float(ci_low), float(ci_high), float(res.pvalues["AGE"])


def _row(label: str, metric: str, unadjusted, adjusted) -> str:
    return (
        f"{label} & {metric} & "
        f"{format_est_ci_cell(*unadjusted[:3])} & {format_p_value(unadjusted[3])} & "
        f"{format_est_ci_cell(*adjusted[:3])} & {format_p_value(adjusted[3])}\\\\"
    )


def build_table_tex(mod, agg, *, n_participants: int, n_intervals: int) -> str:
    vessel_cov = mod.covariate_terms(agg, include_vessel_length=False)
    count_cov = mod.covariate_terms(agg, include_vessel_length=True)
    vessel_uni = _age_effect(mod, agg, "total_vessel_length", [])
    vessel_multi = _age_effect(mod, agg, "total_vessel_length", vessel_cov)
    count_uni = _age_effect(mod, agg, "n_total", [])
    count_multi = _age_effect(mod, agg, "n_total", count_cov)
    lines = [
        "% Auto-generated by statistics/13_Table_age_related_visibility.py",
        f"% participants: {n_participants}; intervals: {n_intervals}",
        "% adjusted a: sex, ethnicity_group, TIV_cuberoot",
        "% adjusted b: sex, ethnicity_group, TIV_cuberoot, total_vessel_length",
        r"\begin{tabular}{llcccc}\toprule",
        r"  && \multicolumn{2}{c}{Unadjusted}&  \multicolumn{2}{c}{Adjusted}\\",
        r"  &Effect metric& Estimate [95\% CI]& $p$ & Estimate [95\% CI]&$p$ \\ ",
        r" \midrule",
        _row(r"Total vessel length (mm)", r"$\beta$ (mm/year)", vessel_uni, vessel_multi),
        _row(r"Segment count", r"$\beta$ (/year)", count_uni, count_multi),
        r"\bottomrule",
        r"\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    mod = _load_visibility()
    agg, csv_path = mod.load_participant_frame(mod.PROJECT_ROOT)
    tex = build_table_tex(
        mod,
        agg,
        n_participants=len(agg),
        n_intervals=int(agg["n_total"].sum()),
    )
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TEX.write_text(tex, encoding="utf-8")
    print(f"input: {csv_path}")
    print(f"Wrote: {OUT_TEX}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""Generate paper table: Table_m1_piecewise_models_rho."""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

STATISTICS_ROOT = Path(__file__).resolve().parents[1]
TABLES_ROOT = STATISTICS_ROOT / "tables"
if str(TABLES_ROOT) not in sys.path:
    sys.path.insert(0, str(TABLES_ROOT))

from table_format import format_exploratory_p, format_magnitude_latex  # noqa: E402
IN_CSV = STATISTICS_ROOT / "results" / "rho_candidate_breakpoint_piecewise_table.csv"
OUT_TEX = TABLES_ROOT / "Table_m1_piecewise_models_rho.tex"


def format_breakpoint_years(bp: float) -> str:
    return f"{int(round(float(bp)))}"


def format_counts(s: str) -> str:
    return str(s)


def build_latex_piecewise_table(pw_df: pd.DataFrame) -> str:
    required = [
        "breakpoint",
        "pre_breakpoint_slope_beta1",
        "post_breakpoint_slope_beta1_plus_beta2",
        "slope_change_beta2",
        "wald_p_beta2_unadjusted_exploratory",
        "n_<breakpoint>/n_>=breakpoint (participants)",
    ]
    missing = [c for c in required if c not in pw_df.columns]
    if missing:
        raise ValueError(f"Missing columns in piecewise table: {missing}")

    df = pw_df.sort_values("breakpoint").reset_index(drop=True)

    lines: list[str] = []
    lines.append("% Auto-generated by statistics/table_scripts/Table_m1_piecewise_models_rho.py")
    lines.append(r"\begin{tabular}{lccccc}")
    lines.append(r"\toprule")
    lines.append(
        r"Candidate breakpoint (years) & "
        r"Pre-breakpoint slope $\beta_{<\text{breakpoint}}$ & "
        r"Post-breakpoint slope $\beta_{\geq\text{breakpoint}}$ & "
        r"Slope change $\beta_{\geq\text{breakpoint}} - \beta_{<\text{breakpoint}}$ & "
        r"Exploratory $p$ & "
        r"$n_{< \text{breakpoint}} / n_{\ge \text{breakpoint}}$ (participants) \\"
    )
    lines.append(r"\midrule")

    for _, row in df.iterrows():
        cells = [
            format_breakpoint_years(row["breakpoint"]),
            format_magnitude_latex(row["pre_breakpoint_slope_beta1"]),
            format_magnitude_latex(row["post_breakpoint_slope_beta1_plus_beta2"]),
            format_magnitude_latex(row["slope_change_beta2"]),
            format_exploratory_p(row["wald_p_beta2_unadjusted_exploratory"]),
            format_counts(str(row["n_<breakpoint>/n_>=breakpoint (participants)"])),
        ]
        lines.append(" & ".join(cells) + r" \\")

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    return "\n".join(lines) + "\n"


def main() -> None:
    if not IN_CSV.exists():
        raise FileNotFoundError(
            f"Input CSV not found: {IN_CSV}\n"
            "Run: python statistics/03_m1_ols_cluster_multivariable_analysis.py"
        )

    pw_df = pd.read_csv(IN_CSV)
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    tex = build_latex_piecewise_table(pw_df)
    OUT_TEX.write_text(tex, encoding="utf-8")
    print(f"Wrote: {OUT_TEX}")


if __name__ == "__main__":
    main()
